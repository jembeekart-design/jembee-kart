"use client";

import { Suspense, useMemo } from "react";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { ArrowLeft, CalendarDays, ChevronRight, CircleDollarSign, Clock3, ReceiptText, Share2, Video, Wallet } from "lucide-react";
import Header from "@/components/navigation/Header";
import BottomNavbar from "@/components/navigation/BottomNavbar";

type RecordType = "share-earning" | "creator-earning" | "share-history" | "creator-history" | "share-payments" | "creator-payments";

const sections: { id: RecordType; title: string; description: string; icon: typeof Share2; group: "earning" | "history" | "payment" }[] = [
  { id: "share-earning", title: "Share Earnings", description: "Earnings generated through your shared videos.", icon: Share2, group: "earning" },
  { id: "creator-earning", title: "Creator Earnings", description: "Earnings generated by your uploaded videos.", icon: Video, group: "earning" },
  { id: "share-history", title: "Share Earnings History", description: "Daily records and date-wise share earning details.", icon: CalendarDays, group: "history" },
  { id: "creator-history", title: "Creator Earnings History", description: "Daily records and date-wise creator earning details.", icon: CalendarDays, group: "history" },
  { id: "share-payments", title: "Share Payment History", description: "Payment dates, amounts and payment statuses for sharing.", icon: ReceiptText, group: "payment" },
  { id: "creator-payments", title: "Creator Payment History", description: "Payment dates, amounts and payment statuses for uploaded videos.", icon: ReceiptText, group: "payment" },
];

function EarningsContent() {
  const params = useSearchParams();
  const selectedId = params.get("type") as RecordType | null;
  const selected = useMemo(() => sections.find((item) => item.id === selectedId), [selectedId]);

  return (
    <main className="min-h-screen overflow-x-hidden bg-[var(--color-page-background)] pb-32 pt-[105px] md:pt-[140px]">
      <Header />
      <section className="px-4 pt-4">
        <Link href="/account" className="mb-5 inline-flex items-center gap-2 rounded-full bg-[var(--color-card-background)] px-4 py-2 text-sm font-bold text-[var(--text-primary)] shadow-sm"><ArrowLeft size={18} /> Back to Profile</Link>
        <div className="overflow-hidden rounded-[30px] bg-gradient-to-br from-[var(--color-primary-button)] to-[var(--color-primary-button)] p-6 text-[var(--button-text-color)] shadow-lg">
          <div className="flex items-center gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-white/15"><Wallet size={25} /></div>
            <div><p className="text-xs font-bold uppercase tracking-[0.18em] text-white/75">JembeeKart</p><h1 className="mt-1 text-2xl font-black">Earnings &amp; Payments</h1></div>
          </div>
          <p className="mt-4 max-w-sm text-sm leading-6 text-white/80">Review share and creator earnings separately, along with date-wise earning and payment records.</p>
        </div>
      </section>

      {selected ? (
        <section className="mt-6 px-4">
          <div className="rounded-[28px] bg-[var(--color-card-background)] p-5 shadow-sm">
            <div className="flex items-start gap-3">
              <div className="flex h-12 w-12 shrink-0 items-center justify-center rounded-2xl bg-[var(--color-primary-button)]/10 text-[var(--color-primary-button)]"><selected.icon size={23} /></div>
              <div className="min-w-0 flex-1"><h2 className="text-xl font-black text-[var(--text-primary)]">{selected.title}</h2><p className="mt-1 text-sm leading-5 text-[var(--text-secondary)]">{selected.description}</p></div>
            </div>
            <div className="mt-6 rounded-2xl border border-[var(--text-secondary)]/15 p-5 text-center">
              <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-[var(--color-page-background)] text-[var(--text-secondary)]">{selected.group === "payment" ? <ReceiptText size={23} /> : selected.group === "history" ? <CalendarDays size={23} /> : <CircleDollarSign size={23} />}</div>
              <h3 className="mt-3 font-bold text-[var(--text-primary)]">No records to display</h3>
              <p className="mx-auto mt-1 max-w-xs text-sm leading-5 text-[var(--text-secondary)]">Verified {selected.group === "payment" ? "payment records" : "earning records"} will appear here when available.</p>
              <div className="mt-4 inline-flex items-center gap-2 rounded-full bg-[var(--color-page-background)] px-3 py-2 text-xs font-semibold text-[var(--text-secondary)]"><Clock3 size={14} /> Updated records appear here</div>
            </div>
          </div>
        </section>
      ) : (
        <section className="mt-6 space-y-6 px-4">
          {[{ title: "Earnings Overview", description: "Separate earnings by activity", group: "earning" }, { title: "Earning Records", description: "Review earnings by date", group: "history" }, { title: "Payment Records", description: "Track payment dates and statuses", group: "payment" }].map((group) => (
            <div key={group.group}>
              <div className="mb-3"><h2 className="text-lg font-black text-[var(--text-primary)]">{group.title}</h2><p className="mt-1 text-sm text-[var(--text-secondary)]">{group.description}</p></div>
              <div className="space-y-3">
                {sections.filter((item) => item.group === group.group).map((item) => { const Icon = item.icon; return (
                  <Link key={item.id} href={`/account/earnings?type=${item.id}`} className="group flex items-center gap-4 rounded-[24px] border border-[var(--text-secondary)]/10 bg-[var(--color-card-background)] p-4 shadow-sm transition-all hover:-translate-y-0.5 hover:shadow-md">
                    <div className="flex h-12 w-12 shrink-0 items-center justify-center rounded-2xl bg-[var(--color-primary-button)]/10 text-[var(--color-primary-button)]"><Icon size={22} /></div>
                    <div className="min-w-0 flex-1"><h3 className="font-extrabold text-[var(--text-primary)]">{item.title}</h3><p className="mt-1 text-sm leading-5 text-[var(--text-secondary)]">{item.description}</p></div>
                    <ChevronRight size={20} className="shrink-0 text-[var(--text-secondary)] transition-transform group-hover:translate-x-1" />
                  </Link>
                ); })}
              </div>
            </div>
          ))}
          <div className="rounded-2xl border border-[var(--text-secondary)]/10 bg-[var(--color-card-background)] p-4 text-xs leading-5 text-[var(--text-secondary)]">Earnings are shown only after the underlying revenue and user attribution have been verified. This screen does not calculate or promise payouts by views alone.</div>
        </section>
      )}
      <BottomNavbar />
    </main>
  );
}

export default function EarningsPage() {
  return <Suspense fallback={<main className="min-h-screen bg-[var(--color-page-background)] p-6 pt-28 text-sm text-[var(--text-secondary)]">Loading earnings…</main>}><EarningsContent /></Suspense>;
}
